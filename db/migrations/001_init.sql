-- Per-source moderation switch. Launch: everything manual. PR 1 adds schema + defaults only; no code reads it yet.
create table if not exists sources (
  source       activity_source primary key,
  auto_publish boolean not null default false,
  notes        text,
  updated_at   timestamptz not null default now()
);
insert into sources (source) values ('curated'),('ai'),('business'),('community'),('affiliate')
  on conflict (source) do nothing;

create table if not exists submissions (
  id            bigint primary key generated always as identity,
  payload       jsonb not null,             -- proposed activity fields, same shape as activities
  -- PRIVATE: never returned by any public endpoint; only for the future admin dashboard / reward crediting.
  submitter_email citext not null
    check (length(submitter_email) <= 254 and submitter_email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  submitter_user_id uuid,                   -- reserved for accounts later
  status        activity_status not null default 'pending',
  activity_id   integer references activities(id) on delete set null, -- set when approved
  reviewer_note text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists submissions_status_idx on submissions (status, created_at desc);
create index if not exists submissions_email_idx on submissions (submitter_email);  -- reward counting later
comment on column submissions.submitter_email is 'PRIVATE PII: admin-only, never expose publicly';

create or replace function set_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;
drop trigger if exists activities_updated_at on activities;
create trigger activities_updated_at before update on activities for each row execute function set_updated_at();
drop trigger if exists submissions_updated_at on submissions;
create trigger submissions_updated_at before update on submissions for each row execute function set_updated_at();

alter table activities  enable row level security;
alter table submissions enable row level security;
alter table sources     enable row level security;
