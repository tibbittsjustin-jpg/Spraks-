create extension if not exists postgis;
create extension if not exists citext;

do $$ begin
  create type activity_status as enum ('pending','approved','rejected','archived');
  create type activity_source as enum ('curated','ai','business','community','affiliate');
  create type activity_tier   as enum ('free','paid');
exception when duplicate_object then null; end $$;

create table if not exists activities (
  id            integer primary key generated by default as identity,
  title         text not null,
  description   text not null default '',
  category      text not null,
  icon          text not null default '',
  setting       text not null check (setting in ('Indoor','Outdoor','Both')),
  season        text[] not null default '{}',
  food          boolean not null default false,
  cost          text not null check (cost in ('Free','$1-$10','$20-$30','$100 and under')),
  duration      text not null check (duration in ('Quick (under 1 hr)','Short (1-2 hrs)','Half-day (2-5 hrs)','Full day','Overnight')),
  time          text[] not null default '{}',
  vibe          text[] not null default '{}',
  stage         text[] not null default '{}',
  date_type     text[] not null default '{}',
  scene         text,
  motif         text,
  status        activity_status not null default 'pending',
  source        activity_source not null default 'community',
  tier          activity_tier   not null default 'free',
  address       text,
  location      geography(Point, 4326),
  coords_locked boolean not null default false,  -- true = human-verified; no bot/seed may overwrite address/location
  geo_status    text,                            -- coords file: confident|area_based|route_unpinned|flagged|pending; other values are stored and not pinned
  geo_confidence text,                           -- high|low|manual|null
  geo_source    text,                            -- e.g. nominatim, manual
  geo_resolved_at timestamptz,
  affiliate_url text check (affiliate_url is null or affiliate_url ~ '^https://'),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  approved_at   timestamptz,
  retired_at    timestamptz   -- set when a curated idea is removed from data.js
);
-- curated ids are well below 100000; new identity values must start above them (seed also resets this)
alter table activities alter column id restart with 100000;

-- Defense in depth for locked coords: any UPDATE that changes address/location on a locked row is
-- rejected unless the same statement also sets coords_locked = false (an explicit admin unlock).
create or replace function protect_locked_coords() returns trigger language plpgsql as $$
begin
  if old.coords_locked and new.coords_locked
     and (new.location is distinct from old.location or new.address is distinct from old.address) then
    raise exception 'coords_locked: activity % has locked coordinates', old.id using errcode = 'P0001';
  end if;
  return new;
end $$;
drop trigger if exists activities_protect_locked on activities;
create trigger activities_protect_locked before update on activities for each row execute function protect_locked_coords();

